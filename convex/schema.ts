import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";
export default defineSchema({
  tasks: defineTable({
    userId: v.string(),
    title: v.string(),
    status: v.string(),
    date: v.optional(v.string()),
    completed: v.optional(v.boolean()),
    completedAt: v.optional(v.number()),
    notes: v.optional(v.string()),
    priority: v.optional(v.string()),
    contexts: v.optional(v.array(v.string())),
    recurrenceGenerated: v.optional(v.boolean()),
    recurring: v.optional(v.boolean()),
    recurrenceType: v.optional(v.string()),
    recurrenceInterval: v.optional(v.number()),
    recurrenceDays: v.optional(v.array(v.string())),
    recurrenceCount: v.optional(v.number()),
    recurrenceEndDate: v.optional(v.string()),
    projectId: v.optional(v.id("projects")),
    order: v.optional(v.number()),
    createdAt: v.number(),
  }).index("by_user", ["userId"]),
  projects: defineTable({
    userId: v.string(),
    name: v.string(),
    description: v.optional(v.string()),
    createdAt: v.number(),
  }).index("by_user", ["userId"]),
  reminders: defineTable({
    userId: v.string(),
    title: v.string(),
    notes: v.optional(v.string()),
    date: v.string(),
    time: v.optional(v.string()),
    dismissed: v.boolean(),
    createdAt: v.number(),
  }).index("by_user", ["userId"]),
});
